"""How much is predictable at all, and does history add information? (validation only)

Usage:
    uv run python scripts/diagnose_signal.py

Fits the same kind of model (standardised logistic regression, C = 0.1) on four input sets and
scores each on the VALIDATION students:

1. the 15 snapshot features (median-imputed; the deployed models additionally get three
   missing-value indicators, so their scores differ slightly);
2. snapshot + hand-made history summaries (mean / minimum / recent slope of SGPA, failures so
   far) - tests whether *history information* helps, independently of the LSTM architecture;
3. an ORACLE given the generator's hidden state at time t (ability, trend, current performance
   and engagement) - impossible in reality, but it shows the ceiling: the outcome's remaining
   uncertainty is next-semester randomness that nothing observable at time t can predict;
4. oracle + snapshot.

This is a diagnostic of the synthetic data, not a model for deployment. The hidden variables are
used here only and never as inputs to any deployed model.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from scholartrack.data.curriculum import load_curriculum
from scholartrack.evaluation.metrics import probability_metrics
from scholartrack.features.specs import load_feature_config
from scholartrack.paths import PROJECT_ROOT, REPORTS_DIR, SYNTHETIC_DIR
from scholartrack.reporting import md_table
from scholartrack.targets import load_target_config
from scholartrack.training.data import load_dataset, prepare_data

HISTORY = ["sgpa_mean_to_date", "sgpa_min_to_date", "failed_to_date", "sgpa_slope_last3"]
HIDDEN = ["ability", "trend", "performance", "engagement", "engagement_trait"]


def _slope(values: np.ndarray) -> float:
    return float(np.polyfit(np.arange(len(values)), values, 1)[0])


def add_history(table: pd.DataFrame) -> pd.DataFrame:
    """Past-only summaries: each uses semesters <= t of the same student."""
    t = table.sort_values(["student_key", "semester"]).copy()
    g = t.groupby("student_key")["sgpa_current"]
    t["sgpa_mean_to_date"] = g.transform(lambda s: s.expanding().mean())
    t["sgpa_min_to_date"] = g.transform(lambda s: s.expanding().min())
    t["sgpa_slope_last3"] = g.transform(
        lambda s: s.rolling(3, min_periods=2).apply(_slope, raw=True)
    )
    t["failed_to_date"] = t.groupby("student_key")["n_failed"].cumsum()
    return t


def main() -> None:
    fc = load_feature_config()
    semesters, subjects, _ = load_dataset(SYNTHETIC_DIR)
    prepared = prepare_data(semesters, subjects, load_curriculum(), load_target_config(), fc)
    table = add_history(prepared.table)
    latent = pd.read_csv(SYNTHETIC_DIR / "latent_truth.csv")
    table = table.merge(
        latent[["student_key", "semester", *HIDDEN]], on=["student_key", "semester"], how="left"
    )
    labelled = table[table["label_status"] == "labelled"]
    train = labelled[labelled["partition"] == "train"]
    val = labelled[labelled["partition"] == "validation"]

    snapshot = list(fc.snapshot_features)
    input_sets = {
        "snapshot features": snapshot,
        "snapshot + history summaries": snapshot + HISTORY,
        "ORACLE: hidden state at t": HIDDEN + ["semester"],
        "ORACLE + snapshot": snapshot + HIDDEN,
    }
    rows = []
    for name, cols in input_sets.items():
        medians = train[cols].median()
        model = make_pipeline(StandardScaler(), LogisticRegression(C=0.1, max_iter=5000))
        model.fit(train[cols].fillna(medians), train["label"].astype(int))
        p = model.predict_proba(val[cols].fillna(medians))[:, 1]
        m = probability_metrics(val["label"].astype(int), p)
        rows.append(
            {
                "inputs": name,
                "n inputs": len(cols),
                "log loss": m["log_loss"],
                "Brier": m["brier"],
                "ROC-AUC": m["roc_auc"],
                "PR-AUC": m["pr_auc"],
            }
        )
    result = pd.DataFrame(rows)

    lines = [
        "# Signal Diagnostic (validation only, synthetic data)\n",
        "> Generated by `scripts/diagnose_signal.py`. Same model type (standardised logistic "
        "regression, C = 0.1) on different inputs, scored on the validation students. Rows "
        "marked ORACLE use the generator's hidden variables, which no real system could know; "
        "they show the ceiling, not an achievable model.\n",
        md_table(result, digits=4) + "\n",
        "**How to read it.** If adding history summaries does not improve on the snapshot, the "
        "past beyond the latest two semesters carries little extra information in this data, so "
        "no architecture (including an LSTM) can gain much from it. The gap between the snapshot "
        "and the oracle is the most any model using observable data could still gain; the "
        "oracle's own error is next-semester randomness that cannot be predicted at time t.\n",
    ]
    path = REPORTS_DIR / "signal_diagnostic.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(result.to_string(index=False, float_format=lambda v: f"{v:.4f}"))
    print(f"Wrote {path.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
