"""Generate the ScholarTrack synthetic dataset (Phase 4).

Usage:
    uv run python scripts/generate_synthetic_data.py            # official dataset + profile
    uv run python scripts/generate_synthetic_data.py --seed 7 --out-dir /tmp/syn7 --no-report

Outputs (all Git-ignored, regenerable):
    data/synthetic/semesters.csv          internal representation, one row per student-semester
    data/synthetic/subjects.csv           internal representation, one row per subject result
    data/synthetic/students.csv           synthetic PRN / name for each student key
    data/synthetic/latent_truth.csv       hidden generating variables (NEVER a model input)
    data/synthetic/college_format/*.csv   the same records in the reference CSV layout
    data/synthetic/manifest.json          seed, config hashes, row counts, file hashes
and the committed, aggregate-only report reports/synthetic_data_profile.md.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from scholartrack import __version__
from scholartrack.data.curriculum import load_curriculum
from scholartrack.data.loader import read_college_csv
from scholartrack.data.validation import validate_college_frame
from scholartrack.paths import CONFIG_DIR, PROJECT_ROOT, REFERENCE_CSV, REPORTS_DIR, SYNTHETIC_DIR
from scholartrack.reporting import fmt, md_table
from scholartrack.synthetic.generator import (
    SyntheticDataset,
    generate,
    load_synthetic_config,
    to_college_format,
)
from scholartrack.targets import (
    load_target_config,
    next_semester_labels,
    semester_outcomes,
    subject_outcomes,
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_dataset(ds: SyntheticDataset, wide: dict, out_dir: Path) -> dict[str, dict]:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "college_format").mkdir(exist_ok=True)
    files = {
        "semesters.csv": ds.semesters,
        "subjects.csv": ds.subjects,
        "students.csv": ds.students[["student_key", "prn", "student_name", "cohort", "division"]],
        "latent_truth.csv": ds.latent,
    }
    for (year, semester), frame in sorted(wide.items()):
        files[f"college_format/{year}_sem{semester}.csv"] = frame
    written = {}
    for name, frame in files.items():
        path = out_dir / name
        frame.to_csv(path, index=False, lineterminator="\n")
        written[name] = {"rows": len(frame), "sha256": sha256(path)}
    return written


def build_profile(ds: SyntheticDataset, wide: dict, manifest: dict) -> str:
    curriculum = load_curriculum()
    target = load_target_config()
    cfg = ds.config
    out_sem = semester_outcomes(subject_outcomes(ds.subjects, curriculum.grading), target)
    labels = next_semester_labels(out_sem, target)
    labelled = labels[labels["label_status"] == "labelled"]

    lines: list[str] = []
    w = lines.append
    w("# Synthetic Data Profile\n")
    w(
        "> Generated by `scripts/generate_synthetic_data.py`. Every number below is computed "
        "from the generated files. **All data here is synthetic**; comparisons with the "
        "reference file describe similarity of *format and summary statistics* only, not "
        "representativeness of real students.\n"
    )

    w("## 1. Run facts\n")
    facts = pd.DataFrame(
        [
            ("Seed", str(cfg["seed"])),
            ("Generator version", str(cfg["generator_version"])),
            ("ScholarTrack version", __version__),
            ("Config SHA-256", f"`{manifest['config_sha256'][:16]}…`"),
            ("Students", str(len(ds.students))),
            ("Cohorts (admission year)", ", ".join(map(str, cfg["population"]["cohorts"]))),
            ("Student-semester records", str(len(ds.semesters))),
            ("Subject results", str(len(ds.subjects))),
            ("College-format files", str(len(wide))),
        ],
        columns=["Item", "Value"],
    )
    w(md_table(facts) + "\n")

    w("## 2. Records per cohort and semester\n")
    joined = ds.semesters.merge(ds.students[["student_key", "cohort"]], on="student_key")
    grid = joined.pivot_table(
        index="cohort", columns="semester", values="student_key", aggfunc="count", fill_value=0
    )
    grid.columns = [f"sem {c}" for c in grid.columns]
    w(md_table(grid.reset_index()) + "\n")
    w(
        "Cohort 2024 stops at semester 5 (academic year 2026-27), matching the reference file; "
        "cohort 2023 stops at semester 7; earlier cohorts are complete. Counts fall slightly "
        "over time because some students leave (§3).\n"
    )

    w("## 3. Hidden structure (from `latent_truth.csv`)\n")
    traj = ds.students["trajectory"].value_counts(normalize=True).rename("share")
    left = ds.latent.groupby("student_key")["left_after_semester"].any()
    st = ds.students.set_index("student_key").assign(left=left)
    by_traj = st.groupby("trajectory").agg(
        students=("cohort", "size"), left_programme=("left", "mean")
    )
    by_traj["share"] = traj
    w(md_table(by_traj.reset_index()[["trajectory", "students", "share", "left_programme"]]) + "\n")
    n_shocks = int((ds.latent["shock"] < 0).sum())
    poor = ds.latent["sgpa_complete_data"] < target.sgpa_threshold
    leave_poor = ds.latent.loc[poor, "left_after_semester"].mean()
    leave_ok = ds.latent.loc[~poor, "left_after_semester"].mean()
    w(
        f"- {left.sum()} of {len(st)} students ({left.mean() * 100:.1f} %) leave the programme "
        "before their last observable semester. Students leave after "
        f"{leave_poor * 100:.1f} % of semesters with SGPA < {fmt(target.sgpa_threshold)} versus "
        f"{leave_ok * 100:.1f} % of other semesters — leaving follows poor results, so excluding "
        "leavers' missing futures slightly flatters the training data (*informative "
        "censoring*, `docs/TARGET_DEFINITION.md` §6).\n"
        f"- {n_shocks} student-semesters ({n_shocks / len(ds.latent) * 100:.1f} %) are affected by "
        "a temporary shock (including carried-over halves).\n"
    )

    w("## 4. Outcomes and the label\n")
    per_sem = out_sem.groupby("semester").agg(
        sgpa_mean=("sgpa", "mean"),
        sgpa_sd=("sgpa", "std"),
        failed_any=("n_failed", lambda x: (x > 0).mean()),
        difficulty_rate=("difficulty", "mean"),
    )
    w(md_table(per_sem.reset_index(), digits=3) + "\n")
    status = labels["label_status"].value_counts().rename_axis("label_status")
    w(md_table(status.rename("rows").reset_index()) + "\n")
    prevalence = labelled["label"].mean()
    w(
        f"- **{len(labelled)} labelled rows**; positive (next-semester difficulty) rate "
        f"**{prevalence * 100:.1f} %**. Rows whose next semester is not observed (latest "
        "semester or student left) are unlabelled and will only be *scored*, never trained on.\n"
    )
    lab_traj = labelled.merge(ds.students[["student_key", "trajectory"]], on="student_key")
    w(
        md_table(
            lab_traj.groupby("trajectory")["label"]
            .agg(["mean", "size"])
            .rename(columns={"mean": "positive rate", "size": "rows"})
            .reset_index(),
            digits=3,
        )
        + "\n"
    )

    w("### 4.1 Is the label trivially predictable?\n")
    j = labelled.merge(out_sem[["student_key", "semester", "sgpa"]], on=["student_key", "semester"])
    j["current SGPA band"] = pd.cut(j["sgpa"], [0, 5, 6, 6.5, 7, 7.5, 8, 8.5, 10]).astype(str)
    bands = j.groupby("current SGPA band", sort=False)["label"].agg(["mean", "size"])
    bands = bands.sort_index().rename(columns={"mean": "positive rate", "size": "rows"})
    w(md_table(bands.reset_index(), digits=3) + "\n")
    thresholds = np.arange(4, 9.001, 0.05)
    valid = j.dropna(subset=["sgpa"])
    accs = [((valid["sgpa"] < t) == (valid["label"] == 1)).mean() for t in thresholds]
    best = int(np.argmax(accs))
    majority = max(prevalence, 1 - prevalence)
    w(
        f"The best single cut-off on the *current* SGPA (< {thresholds[best]:.2f}) is right "
        f"{accs[best] * 100:.1f} % of the time, against {majority * 100:.1f} % for always "
        "predicting the majority class. "
        + (
            "Every band contains both outcomes, so the label is "
            if ((bands["positive rate"] > 0) & (bands["positive rate"] < 1)).all()
            else "Some bands contain only one outcome; the label is "
        )
        + "learnable but **not** a deterministic function of the latest SGPA — next-semester "
        "variation that is invisible at prediction time matters. (This is a property of the "
        "data; models are trained and compared only in Phase 6.)\n"
    )

    w("## 5. Missing values (observed vs configured)\n")
    rates = cfg["missingness"]
    miss = []
    for col in (
        "prior_sgpa",
        "study_hours_per_week",
        "commute_time_mins",
        "part_time_job",
        "elective_subject",
        "gender",
        "overall_attendance_pct",
        "credit_weighted_marks_pct",
    ):
        values = ds.semesters[col]
        if col == "prior_sgpa":
            values = values[ds.semesters["semester"] > 1]
        if col == "elective_subject":
            has = ds.semesters["semester"].map(lambda s: bool(curriculum.elective_options.get(s)))
            values = values[has]
        miss.append((col, values.isna().mean(), rates[col]))
    for col in ("attendance_pct", "cie", "termwork", "ete", "total"):
        applicable = ds.subjects[col].notna() | ds.subjects["scheme"].map(
            {
                "theory": col in ("attendance_pct", "cie", "ete", "total"),
                "ete_only": col in ("attendance_pct", "ete", "total"),
                "termwork": col in ("attendance_pct", "termwork", "total"),
            }
        )
        miss.append((f"subject {col}", ds.subjects.loc[applicable, col].isna().mean(), rates[col]))
    miss_df = pd.DataFrame(miss, columns=["field", "observed rate", "configured rate"])
    w(md_table(miss_df, digits=4) + "\n")
    w(
        "`study_hours_per_week` is missing *not* at random: disengaged students skip it more "
        f"often (+{rates['study_hours_extra_if_disengaged']} probability), so its observed rate "
        "exceeds the base rate. `prior_sgpa` is also legitimately absent in semester 1 (no "
        "previous semester) — excluded from the rate above.\n"
    )

    w("## 6. Validation of the college-format exports\n")
    total_issues: dict[tuple[str, str], int] = {}
    for frame in wide.values():
        data = frame.to_csv(index=False).encode("utf-8")
        report = validate_college_frame(read_college_csv(data), curriculum).report
        for issue in report.issues:
            key = (issue.severity, issue.code)
            total_issues[key] = total_issues.get(key, 0) + 1
    if total_issues:
        w(
            md_table(
                pd.DataFrame(
                    [(s, c, n) for (s, c), n in total_issues.items()],
                    columns=["severity", "code", "count"],
                )
            )
            + "\n"
        )
    else:
        w(
            f"All {len(wide)} files pass validation with **no issues of any severity**: every "
            "value is within its permitted range and every derived column is consistent.\n"
        )

    w("## 7. Comparison with the reference file (semester 5, academic year 2026-27)\n")
    if not REFERENCE_CSV.exists():
        w("Reference file not present on this machine — comparison skipped.\n")
        return "\n".join(lines)
    from scholartrack.data.adapter import adapt_college_frame

    ref = adapt_college_frame(read_college_csv(REFERENCE_CSV), curriculum)
    syn5 = ds.semesters[
        (ds.semesters["semester"] == 5) & (ds.semesters["academic_year"] == "2026-27")
    ]
    ref_s = ref.semesters
    w(
        f"Synthetic: {len(syn5)} cohort-2024 students in semester 5. Reference: "
        f"{len(ref_s)} rows (invalid values removed). Same columns, subject codes, credits and "
        "schemes.\n"
    )
    numeric = [
        "prior_sgpa",
        "credit_weighted_marks_pct",
        "overall_attendance_pct",
        "study_hours_per_week",
        "commute_time_mins",
        "age",
    ]
    comp = []
    for col in numeric:
        a, b = ref_s[col].astype(float), syn5[col].astype(float)
        comp.append(
            (
                col,
                a.mean(),
                b.mean(),
                a.std(),
                b.std(),
                a.min(),
                b.min(),
                a.max(),
                b.max(),
                a.isna().mean() * 100,
                b.isna().mean() * 100,
            )
        )
    w(
        md_table(
            pd.DataFrame(
                comp,
                columns=[
                    "field",
                    "mean ref",
                    "mean syn",
                    "sd ref",
                    "sd syn",
                    "min ref",
                    "min syn",
                    "max ref",
                    "max syn",
                    "missing % ref",
                    "missing % syn",
                ],
            )
        )
        + "\n"
    )
    key = ["prior_sgpa", "overall_attendance_pct", "study_hours_per_week", "commute_time_mins"]
    corr = [
        (
            c,
            ref_s[[c, "credit_weighted_marks_pct"]].corr().iloc[0, 1],
            syn5[[c, "credit_weighted_marks_pct"]].corr().iloc[0, 1],
        )
        for c in key
    ]
    w("Correlation with `credit_weighted_marks_pct`:\n")
    w(md_table(pd.DataFrame(corr, columns=["field", "reference", "synthetic"])) + "\n")
    ref_out = semester_outcomes(subject_outcomes(ref.subjects, curriculum.grading), target)
    syn5_keys = set(syn5["student_key"])
    syn_out5 = out_sem[(out_sem["semester"] == 5) & out_sem["student_key"].isin(syn5_keys)]
    rules = pd.DataFrame(
        [
            ("SGPA from marks: mean", ref_out["sgpa"].mean(), syn_out5["sgpa"].mean()),
            ("SGPA from marks: sd", ref_out["sgpa"].std(), syn_out5["sgpa"].std()),
            (
                "failed ≥ 1 subject (%)",
                (ref_out["n_failed"] > 0).mean() * 100,
                (syn_out5["n_failed"] > 0).mean() * 100,
            ),
            (
                "difficulty rule (%)",
                ref_out["difficulty"].mean() * 100,
                syn_out5["difficulty"].mean() * 100,
            ),
        ],
        columns=["semester-5 outcome under the illustrative rules", "reference", "synthetic"],
    )
    w(md_table(rules) + "\n")
    job = pd.DataFrame(
        {
            "reference": ref_s["part_time_job"].value_counts(normalize=True),
            "synthetic": syn5["part_time_job"].value_counts(normalize=True),
        }
    ).rename_axis("part_time_job")
    w(md_table(job.reset_index(), digits=3) + "\n")
    lat4 = ds.latent[(ds.latent["semester"] == 4) & ds.latent["student_key"].isin(syn5_keys)]
    no_fail = lat4["n_failed_complete_data"] == 0
    w("**Reading this comparison.**\n")
    w(
        "- *Same:* columns, subject codes, credits, assessment schemes and value formats.\n"
        "- *Close:* attendance and study-hours levels and spreads, part-time-job share, and the "
        "correlations of prior SGPA, attendance, study hours and commute time with marks.\n"
        f"- *Prior SGPA:* the mean is close, but the synthetic spread is wider "
        f"(sd {syn5['prior_sgpa'].std():.2f} vs {ref_s['prior_sgpa'].std():.2f}). The cause is "
        "failed subjects, which earn 0 grade points: among synthetic students with no failure "
        f"in semester 4 (n = {int(no_fail.sum())}) the sd is "
        f"{lat4.loc[no_fail, 'sgpa_complete_data'].std():.2f} and the minimum "
        f"{lat4.loc[no_fail, 'sgpa_complete_data'].min():.2f}; the {int((~no_fail).sum())} "
        "students with a failure form the low tail. The reference's minimum prior SGPA "
        f"({ref_s['prior_sgpa'].min():.2f}) suggests few failures or a different SGPA "
        "convention in its previous semester.\n"
        "- *Deliberately different:* how widely **current** marks are spread. The reference's "
        "semester-5 marks imply a much lower and wider SGPA than its own `prior_sgpa` "
        "(`reports/data_quality_report.md` §10); the generator keeps consecutive semesters "
        "consistent instead, so its difficulty rate is far lower.\n"
        "- `gender`, `age` and `commute_time_mins` are drawn independently of everything else "
        "and have **no effect** on any outcome; they exist only for schema compatibility.\n"
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=CONFIG_DIR / "synthetic.yaml")
    parser.add_argument("--out-dir", type=Path, default=SYNTHETIC_DIR)
    parser.add_argument("--seed", type=int, default=None, help="override the configured seed")
    parser.add_argument("--no-report", action="store_true")
    args = parser.parse_args()

    cfg = load_synthetic_config(args.config)
    if args.seed is not None:
        cfg["seed"] = args.seed
    curriculum, target = load_curriculum(), load_target_config()
    ds = generate(cfg, curriculum, target)
    wide = to_college_format(ds, curriculum)
    files = write_dataset(ds, wide, args.out_dir)

    manifest = {
        "generator_version": cfg["generator_version"],
        "scholartrack_version": __version__,
        "seed": cfg["seed"],
        "config_sha256": hashlib.sha256(yaml.safe_dump(cfg, sort_keys=True).encode()).hexdigest(),
        "curriculum_sha256": sha256(CONFIG_DIR / "curriculum.yaml"),
        "target_sha256": sha256(CONFIG_DIR / "target.yaml"),
        "synthetic": True,
        "files": files,
    }
    (args.out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(
        f"Wrote {len(files)} files to {args.out_dir} "
        f"({len(ds.semesters)} student-semesters, {len(ds.subjects)} subject results)"
    )

    if not args.no_report:
        REPORTS_DIR.mkdir(exist_ok=True)
        report = REPORTS_DIR / "synthetic_data_profile.md"
        report.write_text(build_profile(ds, wide, manifest), encoding="utf-8")
        print(f"Wrote {report.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
