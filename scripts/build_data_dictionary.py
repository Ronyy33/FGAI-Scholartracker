"""Generate docs/DATA_DICTIONARY.md from the schema, feature specs and configs.

Usage:
    uv run python scripts/build_data_dictionary.py

The dictionary is generated (not hand-written) so it always matches the code; a test fails if
the committed file is out of date.
"""

from __future__ import annotations

import pandas as pd

from scholartrack.data.schema import STUDENT_FIELDS
from scholartrack.features.specs import FEATURE_SPECS, load_feature_config
from scholartrack.paths import PROJECT_ROOT
from scholartrack.reporting import fmt, md_table
from scholartrack.targets import load_target_config

OUTPUT = PROJECT_ROOT / "docs" / "DATA_DICTIONARY.md"

WHEN_KNOWN = {
    "identifier": "always",
    "context": "start of semester",
    "sensitive": "always",
    "candidate": "during / at start of semester",
    "outcome": "end of semester",
}
SUBJECT_FIELDS = [
    (
        "`<CODE>_attendance_pct`",
        "Attendance in the subject",
        "float",
        "%",
        "0–100",
        "during semester",
    ),
    (
        "`<CODE>_CIE_marks`",
        "Continuous internal evaluation marks (theory subjects; 0 / blank for ETE-only subjects)",
        "integer",
        "marks",
        "0–CIE max (40 for 100-mark theory)",
        "during semester",
    ),
    (
        "`<CODE>_ETE_marks`",
        "End-term examination marks",
        "integer",
        "marks",
        "0–ETE max (60 for 100-mark theory; full marks for ETE-only)",
        "end of semester",
    ),
    (
        "`<CODE>_termwork_marks`",
        "Termwork marks (termwork-only subjects)",
        "integer",
        "marks",
        "0–max marks",
        "end of semester",
    ),
    (
        "`<CODE>_total_marks`",
        "Subject total (CIE + ETE, ETE, or termwork)",
        "integer",
        "marks",
        "0–max marks",
        "end of semester",
    ),
    (
        "`<CODE>_max_marks`",
        "Maximum marks of the subject",
        "integer",
        "marks",
        "must equal the curriculum value",
        "always",
    ),
]


def build() -> str:
    fc = load_feature_config()
    target = load_target_config()
    used = set(fc.snapshot_features)
    lines: list[str] = []
    w = lines.append

    w("# Data Dictionary\n")
    w(
        "> Generated by `scripts/build_data_dictionary.py` from `src/scholartrack/data/schema.py`,"
        " `src/scholartrack/features/specs.py`, `configs/features.yaml` and "
        "`configs/target.yaml`. Do not edit by hand.\n"
    )
    w(
        "Three layers: **raw fields** as they appear in a college-format CSV, **engineered "
        "features** the models actually receive, and the **label**. A row of the modelling "
        "table is *one student at the end of semester t*; every feature uses information from "
        "semesters ≤ t only.\n"
    )

    w("## 1. Raw student-level fields\n")
    rows = []
    for spec in STUDENT_FIELDS:
        if spec.minimum is not None:
            permitted = f"{fmt(spec.minimum)}–{fmt(spec.maximum)}"
        elif spec.allowed:
            permitted = ", ".join(spec.allowed)
        elif spec.pattern:
            permitted = f"pattern `{spec.pattern}`"
        else:
            permitted = "free text"
        rows.append(
            {
                "field": f"`{spec.name}`",
                "meaning": spec.description,
                "type": spec.kind,
                "unit": spec.unit or "—",
                "permitted": permitted,
                "role": spec.role,
                "when known": WHEN_KNOWN[spec.role],
                "direct model input": "no — " + fc.excluded[spec.name]
                if spec.name in fc.excluded
                else ("yes" if spec.name in used else "via features"),
            }
        )
    w(md_table(pd.DataFrame(rows)) + "\n")

    w("## 2. Raw subject-level fields\n")
    w(
        "Each subject contributes columns named `<CODE>_<field>`, e.g. `CE24PCC301_CIE_marks`. "
        "Subject codes, credits, schemes and maxima come from `configs/curriculum.yaml`. Subject "
        "fields are never model inputs directly; they are summarised into the features of §3.\n"
    )
    w(
        md_table(
            pd.DataFrame(
                SUBJECT_FIELDS,
                columns=["column", "meaning", "type", "unit", "permitted", "when known"],
            )
        )
        + "\n"
    )

    w("## 3. Engineered features (model inputs)\n")
    frows = []
    for name, spec in FEATURE_SPECS.items():
        frows.append(
            {
                "feature": f"`{name}`",
                "meaning": spec.description,
                "type": spec.dtype,
                "unit": spec.unit,
                "range": spec.value_range,
                "known at": spec.available,
                "built from": spec.source,
                "used": "yes" if name in used else "no",
                "missing indicator": "yes" if name in fc.missing_indicators else "no",
            }
        )
    w(md_table(pd.DataFrame(frows)) + "\n")
    w(
        f"- Thresholds inside features (illustrative): low marks < {fmt(fc.low_marks_pct)} %, "
        f"low attendance < {fmt(fc.low_attendance_pct)} %.\n"
        "- Missing values: a `<feature>_missing` indicator (0/1) is added where marked, then "
        "the value is imputed with the **training** median and standardised with the "
        "**training** mean and standard deviation (`src/scholartrack/features/preprocess.py`).\n"
        f"- The **MLP** and **logistic regression** receive these {len(used)} features (+ "
        f"{len(fc.missing_indicators)} indicators) for semester t. The **LSTM** receives the "
        "same vector for each of the student's semesters 1…t, in time order "
        f"(at most {fc.max_sequence_length}).\n"
    )

    w("## 4. Label\n")
    label = pd.DataFrame(
        [
            {
                "name": "`label`",
                "meaning": (
                    "1 if semester t + 1 is an academic-difficulty semester: ≥ 1 failed "
                    f"subject or SGPA < {fmt(target.sgpa_threshold)}; 0 otherwise"
                ),
                "type": "0 / 1 (missing when undeterminable)",
                "known at": "end of semester t + 1",
                "model input": "never",
                "definition": "`docs/TARGET_DEFINITION.md`, `configs/target.yaml`",
            }
        ]
    )
    w(md_table(label) + "\n")
    w(
        "`label_status` records why a row has no label (`future_semester_not_observed`, "
        "`future_outcome_undetermined`); such rows are scored but never used for training or "
        "evaluation.\n"
    )

    w("## 5. Fields deliberately excluded from model inputs\n")
    w(
        md_table(pd.DataFrame([{"field": f"`{k}`", "reason": v} for k, v in fc.excluded.items()]))
        + "\n"
    )
    return "\n".join(lines)


def main() -> None:
    OUTPUT.write_text(build(), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
