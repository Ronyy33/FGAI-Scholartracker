"""Generate reports/data_quality_report.md from the reference CSV.

Usage:
    uv run python scripts/inspect_reference_data.py [path/to/reference.csv]

The report contains aggregate statistics and row numbers only: no PRNs, no names.
It contains no timestamps, so re-running on the same file reproduces it exactly.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from scholartrack import __version__
from scholartrack.data.adapter import adapt_college_frame
from scholartrack.data.curriculum import load_curriculum
from scholartrack.data.loader import read_college_csv
from scholartrack.data.profiling import infer_credits
from scholartrack.data.schema import (
    IDENTIFIER_COLUMNS,
    STUDENT_FIELD_MAP,
    STUDENT_FIELDS,
    subject_columns,
)
from scholartrack.data.validation import validate_college_frame
from scholartrack.paths import PROJECT_ROOT, REFERENCE_CSV, REPORTS_DIR
from scholartrack.reporting import fmt, md_table
from scholartrack.targets import load_target_config, semester_outcomes, subject_outcomes


def build_report(path: Path) -> str:
    curriculum = load_curriculum()
    target = load_target_config()
    data = path.read_bytes()
    raw = read_college_csv(data)
    validation = validate_college_frame(raw, curriculum)
    report = validation.report
    typed = validation.typed
    adapted = adapt_college_frame(raw, curriculum, validation)
    sem, subj = adapted.semesters, adapted.subjects
    grouped = subject_columns(list(raw.columns))
    sem5 = {s.code: s for s in curriculum.semester_subjects(5)}

    out: list[str] = []
    w = out.append

    w("# Data Quality Report — Reference CSV\n")
    w(
        "> Generated by `scripts/inspect_reference_data.py` (ScholarTrack "
        f"{__version__}). Do not edit by hand; re-run the script instead.\n"
        "> Contains aggregate statistics and row numbers only — **no PRNs or names**. "
        "*Row N* means the N-th data row (spreadsheet line N + 1).\n"
    )

    # ------------------------------------------------------------------ 1. File facts
    w("## 1. File facts\n")
    has_bom = data.startswith(b"\xef\xbb\xbf")
    rel = path.relative_to(PROJECT_ROOT) if path.is_relative_to(PROJECT_ROOT) else path.name
    facts = pd.DataFrame(
        [
            ("File", f"`{rel}`"),
            ("SHA-256", f"`{hashlib.sha256(data).hexdigest()}`"),
            ("Size", f"{len(data):,} bytes"),
            ("Encoding", "UTF-8 with byte-order mark" if has_bom else "UTF-8"),
            ("Rows × columns", f"{raw.shape[0]} × {raw.shape[1]}"),
            ("Student-level columns", str(sum(c in STUDENT_FIELD_MAP for c in raw.columns))),
            ("Subjects", f"{len(grouped)} ({sum(len(v) for v in grouped.values())} columns)"),
            ("Semesters present", ", ".join(map(str, sorted(sem["semester"].unique())))),
            ("Academic years", ", ".join(sorted(raw["academic_year"].dropna().unique()))),
            ("Exact duplicate rows", str(int(raw.duplicated().sum()))),
            ("Duplicate (PRN, semester)", str(int(raw.duplicated(["PRN", "semester"]).sum()))),
            (
                "Provenance",
                "Synthetic (stated by the file name and by its owner); origin of the "
                "generating process unknown",
            ),
        ],
        columns=["Item", "Value"],
    )
    w(md_table(facts) + "\n")
    w(
        "The byte-order mark matters: a naive reader would name the first column "
        "`\\ufeffPRN` instead of `PRN`. The loader strips it.\n"
    )

    # ------------------------------------------------------------------ 2. Summary
    w("## 2. Summary of findings\n")
    summary = report.summary()
    w(md_table(summary) + "\n")
    n_bad_rows = len(
        {i.row for i in report.issues if i.row is not None and i.severity in ("error", "invalid")}
    )
    w(
        f"- **{len(report.of('error'))} errors** (rows that cannot be used): none of the rows "
        "lacks an identifier or semester, and there are no duplicate records."
        if not report.of("error")
        else f"- **{len(report.of('error'))} errors** — rows {sorted(report.error_rows)} "
        "are unusable."
    )
    n_invalid = len(report.of("invalid"))
    w(
        f"- **{n_invalid} impossible values** in {n_bad_rows} different rows"
        + (" (no row has more than one)" if n_bad_rows == n_invalid else "")
        + ". The adapter treats them as missing; it does not guess replacements."
    )
    warn_counts = pd.Series([i.code for i in report.of("warning")]).value_counts()
    w(
        f"- **{len(report.of('warning'))} warnings**: "
        + ", ".join(f"{n} × `{code}`" for code, n in warn_counts.items())
        + "."
    )
    w(
        "- No column contains a pre-computed risk score or future outcome, so there is no "
        "existing label to (mis)use. **The file has no outcome variable**: a label must be "
        "derived from a documented rule (see `docs/TARGET_DEFINITION.md`)."
    )
    w(
        "- The problems look deliberately planted (isolated, clearly impossible values such as "
        "145 % attendance, SGPA 12.4, -5 marks); they make the file a good test of the "
        "validator.\n"
    )

    # ------------------------------------------------------------------ 3. Columns
    w("## 3. Student-level columns\n")
    rows = []
    for spec in STUDENT_FIELDS:
        if spec.name not in raw.columns:
            continue
        col = raw[spec.name]
        entry = {
            "column": f"`{spec.name}`",
            "role": spec.role,
            "kind": spec.kind,
            "missing": int(col.isna().sum()),
            "unique": int(col.nunique()),
            "min": "",
            "mean": "",
            "max": "",
            "permitted": (
                f"{fmt(spec.minimum)}–{fmt(spec.maximum)}"
                if spec.minimum is not None
                else (", ".join(spec.allowed) if spec.allowed else "")
            ),
        }
        if spec.kind in ("numeric", "integer"):
            v = typed[spec.name]
            entry.update(min=fmt(v.min()), mean=fmt(v.mean()), max=fmt(v.max()))
        rows.append(entry)
    w(md_table(pd.DataFrame(rows)) + "\n")
    w(
        "Values are shown **as found** (before invalid values are removed). "
        "Roles: *identifier* never used by models; *sensitive* excluded by default; "
        "*outcome* = measured at the end of the semester.\n"
    )
    names = raw["student_name"]
    w(
        f"Identifiers: `PRN` is unique in all {raw['PRN'].nunique()} rows and follows one "
        f"pattern (`{_pattern(raw['PRN'])}`); `student_name` has {names.nunique()} distinct "
        f"values, so {int(names.duplicated().sum())} rows share a name with another row — "
        "names cannot identify a record, PRNs can. Neither appears in this report.\n"
    )

    # ------------------------------------------------------------------ 4. Subjects
    w("## 4. Subject structure\n")
    sub_rows = []
    pct = pd.DataFrame(
        {code: typed[f["total"]] / typed[f["max_marks"]] * 100 for code, f in grouped.items()}
    )
    for code, fields in grouped.items():
        spec = sem5.get(code)
        sub_rows.append(
            {
                "subject": code,
                "scheme": spec.scheme if spec else "?",
                "max marks": fmt(typed[fields["max_marks"]].iloc[0]),
                "columns": ", ".join(sorted(fields)),
                "credits (config)": fmt(spec.credits) if spec else "?",
                "mean total %": fmt(pct[code].mean(), 1),
                "sd": fmt(pct[code].std(), 1),
                "% below 40": fmt((pct[code] < 40).mean() * 100, 1),
            }
        )
    w(md_table(pd.DataFrame(sub_rows)) + "\n")
    w(
        "Three assessment schemes appear: **theory** (CIE out of 40 + ETE out of 60), "
        "**ETE-only** (`OEL310`, `AEC311`: their CIE column is 0 in every row, so CIE is "
        "treated as *not applicable*, not as a zero score), and **termwork-only**. "
        "The 40/60 split is inferred from the observed maxima.\n"
    )

    # ------------------------------------------------------------------ 5. Credits
    w("## 5. Recovering credits and checking derived columns\n")
    clean_pct = pd.DataFrame(
        {
            code: subj.query("subject_code == @code").set_index("student_key")["total_pct"]
            for code in grouped
        }
    )
    clean_att = pd.DataFrame(
        {
            code: subj.query("subject_code == @code").set_index("student_key")["attendance_pct"]
            for code in grouped
        }
    )
    sem_idx = sem.set_index("student_key")
    by_marks = infer_credits(clean_pct, sem_idx["credit_weighted_marks_pct"])
    by_att = infer_credits(clean_att, sem_idx["overall_attendance_pct"])
    credit_table = pd.DataFrame(
        {
            "subject": list(grouped),
            "weight (marks fit)": [by_marks.weights[c] for c in grouped],
            "credits (marks fit)": [by_marks.credits[c] for c in grouped],
            "credits (attendance fit)": [by_att.credits[c] for c in grouped],
            "credits (config)": [sem5[c].credits if c in sem5 else np.nan for c in grouped],
        }
    )
    w(
        "The file has no credits column. If `credit_weighted_marks_pct` really is a "
        "credit-weighted mean of subject percentages, a least-squares fit recovers the credits "
        "(weights rescaled so the lightest subject = 1):\n"
    )
    w(md_table(credit_table, digits=4) + "\n")
    agree = (credit_table["credits (marks fit)"] == credit_table["credits (config)"]).all() and (
        credit_table["credits (attendance fit)"] == credit_table["credits (config)"]
    ).all()
    w(
        f"- Marks fit: {by_marks.n_rows} complete rows; with the rounded credits "
        f"(total {int(by_marks.credits.sum())}) the largest error is "
        f"{by_marks.max_abs_residual:.3f} points (RMSE {by_marks.rmse:.3f}) — i.e. rounding "
        "to one decimal place."
    )
    w(
        f"- Attendance fit: {by_att.n_rows} complete rows; `overall_attendance_pct` is the "
        f"**credit-weighted** (not simple) mean of subject attendance; largest error "
        f"{by_att.max_abs_residual:.3f} points."
    )
    w(
        "- Both fits give the same credits, and they match `configs/curriculum.yaml`: "
        f"**{'yes' if agree else 'NO — investigate'}**.\n"
    )

    # ------------------------------------------------------------------ 6. Issues
    w("## 6. Every validation issue\n")
    issues = report.to_frame()
    issues["row"] = issues["row"].map(lambda r: "column" if pd.isna(r) else str(int(r)))
    w(md_table(issues[["severity", "code", "row", "column", "message"]]) + "\n")

    w("### 6.1 Which value is wrong when a total does not add up?\n")
    w(
        "Five rows have a component (CIE, ETE or termwork) that is out of range, so the "
        "subject total no longer equals the sum of its parts. In every case the *total* is "
        "in range, and recomputing `credit_weighted_marks_pct` from the totals reproduces the "
        "reported value to rounding precision (last column), which suggests the totals are "
        "the original values and the components were altered afterwards. The pipeline still "
        "does **not** back-calculate a 'corrected' component: it marks the component missing "
        "and keeps the valid total.\n"
    )
    credits = pd.Series({c: sem5[c].credits for c in grouped if c in sem5})
    recomputed = (pct[credits.index] * credits).sum(axis=1, min_count=len(credits)) / credits.sum()
    cwm_gap = (recomputed - typed["credit_weighted_marks_pct"]).abs()
    comp_rows = []
    for issue in report.of("invalid"):
        if issue.column and any(
            issue.column.endswith(s) for s in ("_CIE_marks", "_ETE_marks", "_termwork_marks")
        ):
            code = issue.column.split("_")[0]
            r = issue.row - 1
            comp_rows.append(
                {
                    "row": issue.row,
                    "column": issue.column,
                    "value": issue.value,
                    "total": fmt(typed.at[r, grouped[code]["total"]]),
                    "max": fmt(typed.at[r, grouped[code]["max_marks"]]),
                    "abs. diff., recomputed vs reported credit-weighted %": fmt(cwm_gap.iloc[r], 3),
                }
            )
    w(md_table(pd.DataFrame(comp_rows)) + "\n")

    # ------------------------------------------------------------------ 7. Missing values
    w("## 7. Missing values (as found)\n")
    missing = raw.isna().sum()
    missing = missing[missing > 0].rename("missing").reset_index()
    missing.columns = ["column", "missing"]
    missing["note"] = missing["column"].map(
        lambda c: (
            "stray column (see §6)"
            if c.endswith("_termwork_marks") and c.split("_")[0] in ("CE24OEL310", "CE24AEC311")
            else ""
        )
    )
    w(md_table(missing) + "\n")
    regular = raw.drop(columns=[c for c in missing.query("note != ''")["column"]])
    per_row = regular.isna().sum(axis=1)
    n_blank, n_rows_blank = int(per_row.sum()), int((per_row > 0).sum())
    w(
        f"Apart from the two stray columns, {n_blank} cells are blank, spread over "
        f"{n_rows_blank} rows (at most {int(per_row.max())} per row) and "
        f"{int((regular.isna().sum() > 0).sum())} columns — scattered gaps with no visible "
        "pattern, consistent with random omissions rather than a systematic recording "
        "problem.\n"
    )

    # ------------------------------------------------------------------ 8. Categories
    w("## 8. Categorical distributions\n")
    for column in (
        "class_division",
        "semester",
        "elective_subject",
        "part_time_job",
        "gender",
        "age",
    ):
        counts = raw[column].fillna("(missing)").value_counts().rename_axis(column)
        w(md_table(counts.rename("rows").reset_index()) + "\n")
    w(
        "`gender` and `age` are *sensitive* fields: they are profiled here only to document the "
        "file. One-third of rows are 'Prefer not to say', which a real dataset would need to "
        "respect; these fields are excluded from model inputs by default.\n"
    )

    # ------------------------------------------------------------------ 9. Relationships
    w("## 9. Relationships between key variables (invalid values removed)\n")
    key_cols = [
        "prior_sgpa",
        "credit_weighted_marks_pct",
        "overall_attendance_pct",
        "study_hours_per_week",
        "commute_time_mins",
    ]
    corr = sem[key_cols].corr().round(2)
    corr.insert(0, "", [f"`{c}`" for c in corr.index])
    w(md_table(corr) + "\n")
    job = sem.groupby("part_time_job")[["credit_weighted_marks_pct", "study_hours_per_week"]]
    job = job.agg(["mean", "count"]).round(2)
    job.columns = [" ".join(c) for c in job.columns]
    w(md_table(job.reset_index()) + "\n")
    raw_corr = typed[key_cols].corr()
    target_col = "credit_weighted_marks_pct"

    def r(col: str) -> str:
        return f"{corr.at[col, target_col]:.2f} (raw data: {raw_corr.at[col, target_col]:.2f})"

    w(
        f"- Correlation with `{target_col}` after removing invalid values: prior SGPA "
        f"{r('prior_sgpa')}, study hours {r('study_hours_per_week')}, attendance "
        f"{r('overall_attendance_pct')}, commute time {r('commute_time_mins')}."
    )
    w(
        "- Removing just 12 impossible values visibly strengthens the relationships — a "
        "concrete example of why validation comes before modelling."
    )
    w(
        "- Part-time work shows only a small difference in mean marks. All of these are "
        "associations in synthetic data, not causes.\n"
    )

    # ------------------------------------------------------------------ 10. Label realism
    w("## 10. What an illustrative 'difficulty' rule would say about this file\n")
    outcomes = semester_outcomes(subject_outcomes(subj, curriculum.grading), target)
    derived_sgpa = outcomes["sgpa"]
    prior = sem["prior_sgpa"]
    qs = [0.1, 0.25, 0.5, 0.75, 0.9]
    comp = pd.DataFrame(
        {
            "statistic": ["mean", "sd"] + [f"{int(q * 100)}th percentile" for q in qs],
            "prior_sgpa (as given)": [prior.mean(), prior.std(), *prior.quantile(qs)],
            "SGPA derived from this semester's marks": [
                derived_sgpa.mean(),
                derived_sgpa.std(),
                *derived_sgpa.quantile(qs),
            ],
        }
    )
    w(
        "Applying the illustrative grading rules in `configs/curriculum.yaml` (pass = total ≥ "
        "40 % and ETE ≥ 40 %; 10-point grade scale) to the semester-5 marks gives an SGPA for "
        "each student, which can be compared with the file's own `prior_sgpa`:\n"
    )
    w(md_table(comp) + "\n")
    labelled = outcomes["difficulty"].notna()
    joined = outcomes.merge(sem[["student_key", "prior_sgpa"]], on="student_key")
    mid = joined["prior_sgpa"].between(6.5, 7.5)
    n_mid, mid_fail = int(mid.sum()), float((joined.loc[mid, "n_failed"] > 0).mean())
    w(
        f"- Under the rule *fail ≥ 1 subject OR SGPA < {fmt(target.sgpa_threshold)}*, "
        f"**{outcomes['difficulty'][labelled].mean() * 100:.1f} %** of the "
        f"{int(labelled.sum())} determinable students would be 'in difficulty' "
        f"({int((outcomes['n_failed'] > 0).sum())} fail at least one subject)."
    )
    w(
        "- **Internal inconsistency:** the previous semester's SGPA is tightly clustered "
        f"(sd {prior.std():.2f}) while this semester's marks imply a far wider spread "
        f"(sd {derived_sgpa.std():.2f}). Among the {n_mid} students whose prior SGPA is between "
        f"6.5 and 7.5, {mid_fail * 100:.0f} % fail at least one subject this semester. Real "
        "cohorts usually change less abruptly from one semester to the next.\n"
        "- **Consequence for Phase 4:** the synthetic generator copies this file's *schema* "
        "(columns, subjects, credits, schemes, value formats) but not its *spread*. It "
        "generates every semester from one consistent process, so each `prior_sgpa` is "
        "exactly the SGPA computed from the previous semester's marks.\n"
    )

    # ------------------------------------------------------------------ 11. Leakage
    w("## 11. Timing of each field and leakage review\n")
    timing = pd.DataFrame(
        [
            ("`prior_sgpa`", "before the semester", "allowed"),
            ("attendance (subject and overall)", "during the semester", "allowed"),
            ("CIE marks", "during the semester", "allowed"),
            ("termwork marks", "end of the semester", "allowed"),
            ("ETE marks, subject totals", "end of the semester", "allowed"),
            ("`credit_weighted_marks_pct`", "end of the semester", "allowed"),
            (
                "`study_hours_per_week`, `part_time_job`, `commute_time_mins`",
                "self-reported",
                "allowed after review (Phase 5)",
            ),
            ("`gender`, `age`", "static", "excluded by default"),
            ("`PRN`, `student_name`", "—", "never"),
            ("anything from semester *t + 1*", "the future", "**never** (that is the label)"),
        ],
        columns=["field", "when it is known", "use for the next-semester target"],
    )
    w(md_table(timing) + "\n")
    w(
        "For the chosen task (end of semester *t* → difficulty in semester *t + 1*), every "
        "semester-*t* column is legitimately known at prediction time. ETE and totals would be "
        "**leakage** only for an *in-semester* early-warning variant that predicts semester "
        "*t*'s own outcome; the code records this timing in `SUBJECT_FIELD_ROLES` "
        "(`src/scholartrack/data/schema.py`).\n"
    )

    # ------------------------------------------------------------------ 12. Privacy
    w("## 12. Privacy notes\n")
    w(
        f"- Direct identifiers present: {', '.join(f'`{c}`' for c in IDENTIFIER_COLUMNS)}. They "
        "are dropped by the adapter, replaced by opaque keys, and never written to reports.\n"
        "- The file is synthetic, but PRNs follow a realistic institutional pattern. It is kept "
        "out of this branch of the public repository (`data/` is Git-ignored); the copy that "
        "was uploaded to `main` remains visible there and in its history until removed.\n"
    )

    # ------------------------------------------------------------------ 13. Decisions
    w("## 13. Decisions taken from this report\n")
    w(
        "1. Validation rules and permitted ranges: `src/scholartrack/data/schema.py`.\n"
        "2. Invalid values → missing, never repaired; rows with errors → dropped and listed.\n"
        "3. Credits and schemes for semester 5 → `configs/curriculum.yaml` (inferred, verified "
        "above).\n"
        "4. ETE-only subjects: CIE is *not applicable*, not zero.\n"
        "5. The two stray `*_termwork_marks` columns for ETE-only subjects are ignored.\n"
        "6. Labels are derived by rule (`configs/target.yaml`); the synthetic generator keeps "
        "the schema but uses a coherent multi-semester process.\n"
    )
    return "\n".join(out)


def _pattern(series: pd.Series) -> str:
    """Describe identifier shape without revealing values: letters→A, digits→9."""
    shapes = series.dropna().str.replace(r"[A-Za-z]", "A", regex=True)
    shapes = shapes.str.replace(r"\d", "9", regex=True)
    return " / ".join(shapes.value_counts().index[:3])


def main() -> None:
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else REFERENCE_CSV
    if not path.exists():
        sys.exit(
            f"Reference CSV not found: {path}. Place it in data/reference/ (see data/README.md)."
        )
    REPORTS_DIR.mkdir(exist_ok=True)
    target = REPORTS_DIR / "data_quality_report.md"
    target.write_text(build_report(path), encoding="utf-8")
    print(f"Wrote {target.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
