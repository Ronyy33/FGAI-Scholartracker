"""Train all models (Phase 6) and save a versioned run.

Usage:
    uv run python scripts/train.py [--config configs/experiment.yaml]

Writes artifacts/<experiment>/<run_id>/ (Git-ignored): preprocessor.json, majority.json,
logistic_regression.json, mlp.pt/.json, lstm.pt/.json, training histories, validation
predictions, metrics.json and manifest.json; updates artifacts/<experiment>/LATEST and the
committed, validation-only reports/training_report.md. The test partition is not used.
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
import torch
import yaml

from scholartrack import __version__
from scholartrack.data.curriculum import load_curriculum
from scholartrack.features.specs import load_feature_config
from scholartrack.paths import CONFIG_DIR, PROJECT_ROOT, REPORTS_DIR
from scholartrack.reporting import fmt, md_table
from scholartrack.targets import load_target_config
from scholartrack.training.data import load_dataset, prepare_data
from scholartrack.training.experiment import run_experiment

ARTIFACTS = PROJECT_ROOT / "artifacts"


def git_state() -> tuple[str, bool]:
    def run(*args: str) -> str:
        return subprocess.run(
            ["git", *args], cwd=PROJECT_ROOT, capture_output=True, text=True, check=False
        ).stdout.strip()

    return run("rev-parse", "--short", "HEAD") or "unknown", bool(run("status", "--porcelain"))


def partition_summary(prepared) -> dict:
    return {
        name: {
            "rows": len(part.y),
            "students": int(part.rows["student_key"].nunique()),
            "positive_rate": float(part.y.mean()),
        }
        for name, part in prepared.partitions.items()
    }


def write_report(run_id: str, results: dict, manifest: dict) -> Path:
    lines: list[str] = []
    w = lines.append
    w("# Training Report (validation only)\n")
    w(
        f"> Generated by `scripts/train.py` for run `{run_id}`. **Synthetic data**: these numbers "
        "measure how well each model recovers the documented synthetic label process, not "
        "real-world predictive ability. The **test partition has not been used**; final test "
        "results come in Phase 7.\n"
    )
    parts = pd.DataFrame(manifest["partitions"]).T.reset_index(names="partition")
    w("## Data\n")
    w(md_table(parts, digits=3) + "\n")
    w(
        f"Dataset manifest SHA-256 `{manifest['dataset']['manifest_sha256'][:16]}…`; "
        f"{len(manifest['feature_names'])} inputs per semester: "
        + ", ".join(f"`{n}`" for n in manifest["feature_names"])
        + ".\n"
    )

    w("## Chosen setting per model family (validation)\n")
    rows = []
    for name, info in results["chosen"].items():
        v = info["validation"]
        rows.append(
            {
                "model": name,
                "settings": json.dumps(info["settings"]),
                "log loss": v["log_loss"],
                "Brier": v["brier"],
                "ROC-AUC": v["roc_auc"],
                "PR-AUC": v["pr_auc"],
                "best epoch": info.get("best_epoch", "—"),
            }
        )
    w(md_table(pd.DataFrame(rows), digits=4) + "\n")
    w(
        f"Validation positive rate: {manifest['partitions']['validation']['positive_rate']:.3f} "
        "— the PR-AUC of a random ranking. Lower log loss / Brier is better; higher ROC-AUC / "
        "PR-AUC is better.\n"
    )

    w("## Seed variation of the chosen networks\n")
    srows = []
    for name in ("mlp", "lstm"):
        spread = results["chosen"][name]["seed_spread"]
        srows.append(
            {
                "model": name,
                "seeds": len(results["chosen"][name]["seeds"]),
                **{f"{k} mean ± sd": f"{v['mean']:.4f} ± {v['sd']:.4f}" for k, v in spread.items()},
            }
        )
    w(md_table(pd.DataFrame(srows)) + "\n")

    w("## Every setting tried\n")
    grid = pd.DataFrame(results["grid"])
    grid["settings"] = grid["settings"].map(json.dumps)
    cols = ["model", "settings", "log_loss", "brier", "roc_auc", "pr_auc"]
    if "best_epoch" in grid:
        grid["best_epoch"] = grid["best_epoch"].map(lambda v: fmt(v))
        grid["seconds"] = grid["seconds"].map(lambda v: fmt(v, 1))
        cols += ["best_epoch", "seconds"]
    w(md_table(grid[cols], digits=4) + "\n")
    path = REPORTS_DIR / "training_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=CONFIG_DIR / "experiment.yaml")
    args = parser.parse_args()
    cfg = yaml.safe_load(args.config.read_text())

    curriculum, target, fconfig = load_curriculum(), load_target_config(), load_feature_config()
    semesters, subjects, dataset_sha = load_dataset(PROJECT_ROOT / cfg["dataset_dir"])
    prepared = prepare_data(semesters, subjects, curriculum, target, fconfig)

    commit, dirty = git_state()
    run_id = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ") + f"-{commit}"
    out_dir = ARTIFACTS / cfg["name"] / run_id
    out_dir.mkdir(parents=True)
    prepared.preprocessor.save(out_dir / "preprocessor.json")

    torch.set_num_threads(4)
    results = run_experiment(prepared, cfg, out_dir)

    manifest = {
        "run_id": run_id,
        "experiment": cfg["name"],
        "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "git_commit": commit,
        "git_dirty": dirty,
        "versions": {
            "python": platform.python_version(),
            "numpy": np.__version__,
            "pandas": pd.__version__,
            "scikit-learn": sklearn.__version__,
            "torch": torch.__version__,
            "scholartrack": __version__,
        },
        "dataset": {"dir": cfg["dataset_dir"], "manifest_sha256": dataset_sha, "synthetic": True},
        "config": cfg,
        "feature_config": fconfig.raw,
        "target": asdict(target),
        "feature_names": prepared.feature_names,
        "partitions": partition_summary(prepared),
        "selection": {"metric": cfg["selection_metric"], "partition": "validation"},
        "test_partition_evaluated": False,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (out_dir / "metrics.json").write_text(json.dumps(results, indent=2) + "\n")
    (ARTIFACTS / cfg["name"] / "LATEST").write_text(run_id + "\n")
    report = write_report(run_id, results, manifest)

    print(f"Run {run_id} saved to {out_dir.relative_to(PROJECT_ROOT)}")
    for name, info in results["chosen"].items():
        v = info["validation"]
        print(
            f"  {name:20s} val log loss {v['log_loss']:.4f}  ROC-AUC {v['roc_auc']:.4f}  "
            f"PR-AUC {v['pr_auc']:.4f}  settings {info['settings']}"
        )
    print(f"Wrote {report.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
