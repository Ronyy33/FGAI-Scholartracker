"""Global explanations: logistic-regression coefficients and permutation importance.

Usage:
    uv run python scripts/explain_global.py

Permutation importance (VALIDATION data): shuffle one indicator across students (with its
missing-value flag) and measure how much ROC-AUC drops; repeated 5 times. A large drop means the
model leans on that indicator. For the LSTM only the current-semester value is shuffled.
Importance is about the model, not about causes. Writes reports/explanations.md.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from scholartrack.data.curriculum import load_curriculum
from scholartrack.evaluation.runner import latest_run_dir
from scholartrack.explain import GROUPS, LABELS, typical_vector
from scholartrack.features.specs import load_feature_config
from scholartrack.models.artifacts import load_run
from scholartrack.paths import PROJECT_ROOT, REPORTS_DIR, SYNTHETIC_DIR
from scholartrack.reporting import md_table
from scholartrack.targets import load_target_config
from scholartrack.training.data import load_dataset, prepare_data

REPEATS, SEED = 5, 20261020


def main() -> None:
    run_dir = latest_run_dir()
    run = load_run(run_dir)
    semesters, subjects, _ = load_dataset(SYNTHETIC_DIR)
    prep = prepare_data(
        semesters, subjects, load_curriculum(), load_target_config(), load_feature_config()
    )
    val = prep.partitions["validation"]
    names = run.preprocessor.output_names
    groups = {
        f: [names.index(f)] + ([names.index(f"{f}_missing")] if f"{f}_missing" in names else [])
        for f in run.preprocessor.features
    }
    rng = np.random.default_rng(SEED)

    rows = []
    for name in ("logistic_regression", "mlp", "lstm"):
        predictor = run.predictors[name]
        last = val.lengths - 1
        base = roc_auc_score(val.y, predictor.predict_proba(val.x, val.seq, val.lengths))
        for feature, cols in groups.items():
            drops = []
            for _ in range(REPEATS):
                perm = rng.permutation(len(val.y))
                x = val.x.copy()
                x[:, cols] = val.x[perm][:, cols]
                seq = val.seq.copy()
                seq[np.arange(len(seq)), last] = x
                p = predictor.predict_proba(x, seq, val.lengths)
                drops.append(base - roc_auc_score(val.y, p))
            rows.append({"model": name, "feature": feature, "auc_drop": float(np.mean(drops))})
    perm = pd.DataFrame(rows).pivot(index="feature", columns="model", values="auc_drop")
    perm = perm.sort_values("logistic_regression", ascending=False)
    perm.insert(0, "indicator", [LABELS[f] for f in perm.index])

    # Concept-group effects (as shown per student in the app), summarised on validation.
    table = prep.table
    rows_val = table[
        (table["partition"] == "validation") & (table["label_status"] == "labelled")
    ].reset_index(drop=True)
    base = typical_vector(run.preprocessor)
    group_rows = []
    for name in ("logistic_regression", "mlp"):
        predictor = run.predictors[name]
        p0 = predictor.predict_proba(val.x)
        for key, (label, features) in GROUPS.items():
            cols = [names.index(f) for f in features] + [
                names.index(f"{f}_missing") for f in features if f"{f}_missing" in names
            ]
            x = val.x.copy()
            x[:, cols] = base[cols]
            effect = 100 * (p0 - predictor.predict_proba(x))
            subset = {
                "results": rows_val["n_failed"] > 0,
                "attendance": rows_val["attendance_pct"] < 75,
            }.get(key)
            if subset is None:
                continue
            group_rows.append(
                {
                    "model": name,
                    "group": label,
                    "students": "with a failed subject"
                    if key == "results"
                    else "with attendance < 75 %",
                    "n": int(subset.sum()),
                    "mean effect (points)": float(effect[subset].mean()),
                    "share where it raises risk": float((effect[subset] > 0).mean()),
                }
            )
    groups_table = pd.DataFrame(group_rows)

    lr = json.loads((run_dir / "logistic_regression.json").read_text())
    coef = pd.DataFrame({"input": lr["feature_names"], "coefficient": lr["coef"]})
    coef["odds ratio per +1 sd"] = np.exp(coef["coefficient"])
    coef = coef.reindex(coef["coefficient"].abs().sort_values(ascending=False).index)

    lines = [
        "# Global Explanations (validation data, synthetic)\n",
        f"> Generated by `scripts/explain_global.py` for run `{run_dir.name}`. These describe what "
        "the models rely on; they are associations in synthetic data, **not causes**.\n",
        "## Permutation importance (drop in validation ROC-AUC when the indicator is shuffled)\n",
        md_table(
            perm.reset_index(drop=True).rename(
                columns={"logistic_regression": "logistic regression", "mlp": "MLP", "lstm": "LSTM"}
            ),
            digits=4,
        )
        + "\n",
        "## Concept-group effects for two groups of validation students\n",
        md_table(groups_table, digits=2) + "\n",
        "Grades behave as expected: for students who failed a subject, the results group raises "
        "the estimate in almost every case. Attendance does **not**: given the same grades, "
        "students with lower attendance are estimated as slightly *less* likely to struggle. In "
        "the synthetic generator engagement drives both attendance and marks, so among students "
        "with equal marks, lower attendance signals higher underlying ability (*explaining "
        "away*). The models faithfully reflect this; it is an association, not advice. The app "
        "shows it honestly with a note, and attendance suggestions come from the attendance "
        "guideline (`configs/recommendations.yaml`), not from the model.\n",
        "## Logistic regression coefficients (standardised inputs)\n",
        md_table(coef, digits=3) + "\n",
        "Inputs are standardised (training mean 0, sd 1), so coefficients are comparable: a "
        "positive coefficient raises the estimated risk as the input increases. Correlated inputs "
        "share credit (e.g. current SGPA, credit-weighted marks and failures overlap), so an "
        "individual coefficient's sign can look counter-intuitive while the combined effect is "
        "sensible. `_missing` inputs are 1 when the value was absent.\n",
    ]
    path = REPORTS_DIR / "explanations.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(perm.head(8).to_string(float_format=lambda v: f"{v:.4f}"))
    print(f"Wrote {path.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
