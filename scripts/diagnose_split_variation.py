"""Why do validation and test scores differ? (analysis only — frozen results are not changed)

Usage:
    uv run python scripts/diagnose_split_variation.py

1. Bootstrap (by student) confidence interval of the chosen model's validation ROC-AUC.
2. 7-fold cross-validation BY STUDENT over all labelled rows, refitting logistic regression with
   the chosen setting (C = 0.1): the spread of fold scores shows how much a ~180-student
   partition can vary by chance.
3. Composition checks of validation vs test (error concentration, hidden-trajectory mix).
Writes reports/split_variation.md.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import GroupKFold

from scholartrack.data.curriculum import load_curriculum
from scholartrack.evaluation.classification import student_bootstrap
from scholartrack.evaluation.runner import latest_run_dir, predict_partition
from scholartrack.features.specs import load_feature_config
from scholartrack.paths import PROJECT_ROOT, REPORTS_DIR, SYNTHETIC_DIR
from scholartrack.reporting import md_table
from scholartrack.targets import load_target_config
from scholartrack.training.data import load_dataset, prepare_data


def main() -> None:
    run_dir = latest_run_dir()
    published = json.loads((REPORTS_DIR / "evaluation_metrics.json").read_text())
    _, val = predict_partition(run_dir, "validation")
    _, test = predict_partition(run_dir, "test")

    y, g, p = val["label"].to_numpy(), val["student_key"].to_numpy(), val["logistic_regression"]
    ci_val = student_bootstrap(g, lambda i: {"auc": roc_auc_score(y[i], p.to_numpy()[i])}, 1000, 1)[
        "auc"
    ]

    semesters, subjects, _ = load_dataset(SYNTHETIC_DIR)
    prep = prepare_data(
        semesters, subjects, load_curriculum(), load_target_config(), load_feature_config()
    )
    parts = [prep.partitions[name] for name in ("train", "validation", "test")]
    x = np.vstack([q.x for q in parts])
    labels = np.concatenate([q.y for q in parts])
    groups = np.concatenate([q.rows["student_key"].to_numpy() for q in parts])
    folds = []
    for train_idx, eval_idx in GroupKFold(n_splits=7, shuffle=True, random_state=0).split(
        x, labels, groups
    ):
        model = LogisticRegression(C=0.1, max_iter=5000).fit(x[train_idx], labels[train_idx])
        folds.append(roc_auc_score(labels[eval_idx], model.predict_proba(x[eval_idx])[:, 1]))

    latent = pd.read_csv(SYNTHETIC_DIR / "latent_truth.csv")
    per_student = latent.groupby("student_key").agg(
        trajectory=("trajectory", "first"), shocks=("shock", lambda s: int((s < 0).sum()))
    )
    rows = []
    for name, part in (("validation", val), ("test", test)):
        err = (part["label"] - part["logistic_regression"]) ** 2
        by_student = err.groupby(part["student_key"]).sum().sort_values(ascending=False)
        traits = per_student.loc[part["student_key"].unique()]
        mix = traits["trajectory"].value_counts(normalize=True)
        rows.append(
            {
                "partition": name,
                "students": part["student_key"].nunique(),
                "positive rate": part["label"].mean(),
                "LR ROC-AUC": roc_auc_score(part["label"], part["logistic_regression"]),
                "error share of worst 10 students": by_student.head(10).sum() / by_student.sum(),
                "declining share": mix.get("declining", 0),
                "shocks per student": traits["shocks"].mean(),
            }
        )

    lr_test = published["models"]["logistic_regression"]
    lines = [
        "# Validation vs Test: Split Variation (analysis only)\n",
        "> Generated by `scripts/diagnose_split_variation.py`. This analysis explains the gap "
        "between validation and test scores; it does **not** change any frozen choice or "
        "published test result.\n",
        f"- Validation ROC-AUC of the chosen model: {rows[0]['LR ROC-AUC']:.3f}, 95 % CI "
        f"[{ci_val[0]:.3f}, {ci_val[1]:.3f}] (bootstrap by student).",
        f"- Test ROC-AUC: {lr_test['probability']['roc_auc']:.3f}, "
        "95 % CI [{:.3f}, {:.3f}].".format(*lr_test["ci95"]["roc_auc"]),
        f"- 7-fold cross-validation by student over all {len(np.unique(groups))} students "
        f"(logistic regression, C = 0.1): fold ROC-AUC from {min(folds):.3f} to {max(folds):.3f}, "
        f"mean {np.mean(folds):.3f}.\n",
        md_table(pd.DataFrame(rows), digits=3) + "\n",
        "**Reading.** The two confidence intervals overlap, and cross-validation shows that a "
        "partition of this size can land anywhere in roughly the fold range above. Validation "
        "fell at the favourable end and test at the unfavourable end; errors are not "
        "concentrated in a few test students. The best single estimate of typical performance "
        "on new synthetic students is the cross-validated mean, with the test result as the "
        "honest, untuned check.\n",
    ]
    path = REPORTS_DIR / "split_variation.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[2:5]))
    print(f"Wrote {path.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
